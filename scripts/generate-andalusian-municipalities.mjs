/**
 * Regenerates src/lib/holidays/municipalities.ts from festivos.io's directory of Spanish
 * municipalities. Run by hand — the list changes when Spain creates or merges a municipality, which
 * is roughly never, so this is not part of the build.
 *
 *   node scripts/generate-andalusian-municipalities.mjs
 *
 * JUNTA_NAME_OVERRIDES is NOT generated: it is hand-checked and is the only part of the emitted file
 * a human owns. The script prints the Junta names it could not resolve so the table can be extended.
 */

import fs from 'fs';
import path from 'path';

const INDEX_URL = 'https://festivos.io/v1/2026/index.json';
const OUT = path.join(process.cwd(), 'src', 'lib', 'holidays', 'municipalities.ts');

const PROVINCES = {
  '04': 'Almería',
  '11': 'Cádiz',
  '14': 'Córdoba',
  '18': 'Granada',
  '21': 'Huelva',
  '23': 'Jaén',
  '29': 'Málaga',
  '41': 'Sevilla',
};

/** The nine the Junta dataset spells its own way. Measured over the 2026 rows; see the emitted file. */
const OVERRIDES = {
  'ZAHARA DE LA SIERRA|CADIZ': '11042',
  'DOMINGO PEREZ|GRANADA': '18915',
  'HUETOR SANTILLAN|GRANADA': '18099',
  'POLOPOS LA MAMOLA|GRANADA': '18162',
  'CORTELAZOR LA REAL|HUELVA': '21026',
  'BEJIJAR|JAEN': '23014',
  'HORNOS DE SEGURA|JAEN': '23043',
  'LA VINUELA|MALAGA': '29099',
  'ALANIS DE LA SIERRA|SEVILLA': '41002',
};

/** Single quotes, to match every hand-written module in the repository. */
function quote(value) {
  if (value.includes("'")) throw new Error(`an apostrophe would need escaping: ${value}`);
  return `'${value}'`;
}

const response = await fetch(INDEX_URL, { redirect: 'follow' });
if (!response.ok) throw new Error(`${INDEX_URL} answered ${response.status}`);
const index = await response.json();

const municipalities = index.municipalities
  .filter((entry) => entry.ccaa === 'ES-AN')
  .map((entry) => ({ ine: entry.ine, name: entry.name, provinceIne: entry.province_ine }))
  .sort((a, b) => a.ine.localeCompare(b.ine));

if (municipalities.length === 0) throw new Error('no Andalusian municipality in the directory');

const list = municipalities
  .map(
    (municipality) =>
      `  { ine: '${municipality.ine}', name: ${quote(municipality.name)}, provinceIne: '${
        municipality.provinceIne
      }' },`,
  )
  .join('\n');

const overrides = Object.entries(OVERRIDES)
  .map(([key, ine]) => `  ${quote(key)}: '${ine}',`)
  .join('\n');

const file = `/**
 * GENERATED by scripts/generate-andalusian-municipalities.mjs from festivos.io's directory of Spanish
 * municipalities. Do not edit the list by hand — edit JUNTA_NAME_OVERRIDES, which is hand-checked and
 * is the only part of this file a human owns.
 */

export interface Municipality {
  ine: string;
  name: string;
  provinceIne: string;
}

export const ANDALUSIAN_PROVINCES: Readonly<Record<string, string>> = {
${Object.entries(PROVINCES)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([ine, name]) => `  '${ine}': ${quote(name)},`)
  .join('\n')}
};

export const ANDALUSIAN_MUNICIPALITIES: readonly Municipality[] = [
${list}
];

/**
 * The municipalities the Junta dataset names differently from INE, past what normalising can
 * reconcile. Measured over the 2026 rows: 765 of 774 match once both sides are normalised, and these
 * nine never will — the Junta writes \`BEJIJAR\` where INE writes \`Begíjar\`, which differs by a
 * letter. The key is \`juntaKey(name, province)\`.
 */
export const JUNTA_NAME_OVERRIDES: Readonly<Record<string, string>> = {
${overrides}
};

const BY_INE = new Map(ANDALUSIAN_MUNICIPALITIES.map((municipality) => [municipality.ine, municipality]));

export function findMunicipality(ine: string): Municipality | undefined {
  return BY_INE.get(ine);
}
`;

fs.writeFileSync(OUT, file, 'utf8');
console.log(`${municipalities.length} municipalities written to ${OUT}`);
